"""The v1 contract the claims board must not break (eng review D5).

Published claims are identified by their hash, and their reproductions point at it: a changed hash orphans every
reproduction. The checked-in claim vectors are regenerated by `arena contracts`, so these pins are literals that a
regeneration cannot quietly move. Threads whose comments carry no account ids must tally exactly as in v1.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from llm_arena.claims import ClaimError, check_claim, trust_stats

VECTORS = Path(__file__).parents[1] / "contracts" / "conformance"

V1_CLAIM = "76765aa9aee49e8dbba7e02d0bc4c7269ac7a9acad4f989b3e768f442f7d687a"
V1_SELF_HOSTED = "5de206f6fe9bd29fa59f3501b91ca57fe227a5b3c18b6675b309fbd5242ad1e7"

# name: (claim_hash, people, passed, trials, above_interval, partial, removed, hidden, [(comment, user, status)])
V1_TALLIES: dict[str, tuple[Any, ...]] = {
    "claim-above-interval": (V1_CLAIM, 3, 4, 6, True, False, 0, 0,
                             [(10, "user0", "counted"), (11, "user1", "counted"), (12, "user2", "counted")]),
    "claim-intact-thread": (V1_CLAIM, 3, 6, 6, False, False, 0, 0,
                            [(21, "carol", "counted"), (22, "dave", "counted"), (30, "bob", "counted")]),
    "claim-mixed-thread": (V1_CLAIM, 2, 3, 4, False, False, 0, 1,
                           [(1, "alice", "author"), (2, "bob", "superseded"), (3, "bob", "counted"),
                            (4, "carol", "counted"), (5, "dave", "edited"), (6, "erin", "rejected"),
                            (8, "gina", "rejected")]),
    "claim-partial-thread": (V1_CLAIM, 3, 4, 6, False, True, 0, 0,
                             [(10, "user0", "counted"), (11, "user1", "counted"), (12, "user2", "counted")]),
    "claim-removed-referenced": (V1_CLAIM, 2, 4, 4, False, False, 1, 0,
                                 [(21, "carol", "counted"), (30, "bob", "counted")]),
    "claim-self-hosted": (V1_SELF_HOSTED, 0, 0, 0, False, False, 0, 0, []),
}  # fmt: skip


def _vector(name: str) -> dict[str, Any]:
    return json.loads((VECTORS / f"{name}.json").read_text())["input"]


@pytest.mark.parametrize("name", sorted(V1_TALLIES))
def test_v1_claims_keep_their_hash_and_tally(name: str) -> None:
    vector = _vector(name)
    chash, people, passed, trials, above, partial, removed, hidden, rows = V1_TALLIES[name]
    check = check_claim(vector["claim"])
    stats = trust_stats(check, vector["comments"], author=vector["author"], total=vector.get("total"))
    assert check.claim_hash == chash
    assert (stats.people, stats.passed, stats.trials) == (people, passed, trials)
    assert (stats.above_interval, stats.partial, stats.removed, stats.hidden) == (above, partial, removed, hidden)
    assert [(r.comment_id, r.user, r.status) for r in stats.rows] == rows


@pytest.mark.parametrize("name", ["claim-hostile-extra-field", "claim-hostile-provider"])
def test_v1_hostile_claims_stay_refused(name: str) -> None:
    with pytest.raises(ClaimError):
        check_claim(_vector(name)["claim"])


def test_existing_claim_vectors_are_never_edited() -> None:
    """New behavior gets new vectors; the v1 ones keep their inputs and expected outputs (D5)."""
    for name in V1_TALLIES:
        expected = json.loads((VECTORS / f"{name}.json").read_text())["expected"]
        assert expected["claim_hash"] == V1_TALLIES[name][0]
        assert expected["stats"]["people"] == V1_TALLIES[name][1]


def _thread(*rows: tuple[int, str, int | None]) -> list[dict[str, Any]]:
    """Comments by (comment id, login, account id) on the v1 vector claim, each reproducing it at 2/2."""
    from llm_arena.conformance import _claim_fixture, _repro_body  # noqa: PLC0415

    body = _repro_body(_claim_fixture(), V1_CLAIM, [1, 1])
    return [{"id": cid, "user": {"login": login, **({"id": uid} if uid else {})},
             "created_at": f"2026-10-10T10:{cid:02d}:00Z", "updated_at": f"2026-10-10T10:{cid:02d}:00Z",
             "body": body} for cid, login, uid in rows]  # fmt: skip


def test_a_renamed_reproducer_stays_one_person() -> None:
    check = check_claim(_vector("claim-mixed-thread")["claim"])
    stats = trust_stats(check, _thread((1, "bob", 7), (2, "bobby", 7)), author="alice", author_id=1)
    assert stats.people == 1
    assert [r.status for r in stats.rows] == ["superseded", "counted"]


def test_a_renamed_author_is_still_excluded_and_ids_win_over_logins() -> None:
    check = check_claim(_vector("claim-mixed-thread")["claim"])
    renamed = trust_stats(check, _thread((1, "alice-new", 1), (2, "carol", 3)), author="alice", author_id=1)
    assert [r.status for r in renamed.rows] == ["author", "counted"] and renamed.people == 1
    # someone who took over the author's old login is a different account, so they count
    taken = trust_stats(check, _thread((1, "alice", 9)), author="alice-new", author_id=1)
    assert [r.status for r in taken.rows] == ["counted"]


def test_comments_without_ids_fall_back_to_logins() -> None:
    check = check_claim(_vector("claim-mixed-thread")["claim"])
    stats = trust_stats(check, _thread((1, "Alice", None), (2, "bob", None), (3, "BOB", None)), author="alice",
                        author_id=1)  # fmt: skip
    assert [r.status for r in stats.rows] == ["author", "superseded", "counted"] and stats.people == 1
